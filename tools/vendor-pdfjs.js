'use strict';
// Puts pdf.js into vendor/pdfjs from an npm package of pdfjs-dist that was downloaded and checked by hand:
//   node tools/vendor-pdfjs.js <folder of the extracted package> <npm integrity sha512-...>
// It copies build/pdf.min.mjs and build/pdf.worker.min.mjs unchanged (used when the page is served over http(s)) and
// writes classic-script copies for a page opened from disk (file://), where browsers refuse ES modules:
//   pdf.classic.js         the library; sets globalThis.pdfjsLib
//   pdf.worker.classic.js  the worker code; sets globalThis.pdfjsWorker, so pdf.js runs it on the page itself
// The only changes: each file is wrapped in an async function (no top-level names leak into the page), `export {...}`
// becomes an assignment, and `import.meta.url` (only used by code that never runs here: Node canvas, image decoders)
// becomes document.baseURI. vendor/pdfjs/VERSION records the source, the integrity and the SHA-256 of every file;
// tests/unit.js checks them.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'vendor', 'pdfjs');

function toClassic(src, globalName) {
  const ex = src.match(/export\s*\{([^}]*)\};?\s*$/);
  if (!ex) throw new Error('no final export {...}');
  let body = src.slice(0, ex.index).replace(/import\.meta\.url/g, '(typeof document !== "undefined" ? document.baseURI : self.location.href)');
  if (/\bimport\.meta\b|^\s*import\s|^\s*export\s/m.test(body)) throw new Error('module syntax left after the conversion');
  const pairs = ex[1].split(',').map((x) => x.trim()).filter(Boolean).map((x) => { const m = x.match(/^(\S+)\s+as\s+(\S+)$/); return m ? `${m[2]}: ${m[1]}` : `${x}: ${x}`; });
  const assign = globalName ? `globalThis.${globalName} = { ${pairs.join(', ')} };` : '';
  return `/* pdf.js as a classic script for pages opened from disk; generated by tools/vendor-pdfjs.js from the .mjs next to it */\n(async function () {\n${body}\n${assign}\n})();\n`;
}

function sha256(f) { return crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex'); }

if (require.main === module) {
  const [pkg, integrity] = process.argv.slice(2);
  if (!pkg || !/^sha512-/.test(integrity || '')) { console.error('usage: node tools/vendor-pdfjs.js <extracted pdfjs-dist folder> <npm integrity sha512-...>'); process.exit(1); }
  const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
  fs.mkdirSync(OUT, { recursive: true });
  for (const f of ['pdf.min.mjs', 'pdf.worker.min.mjs']) fs.copyFileSync(path.join(pkg, 'build', f), path.join(OUT, f));
  fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(OUT, 'LICENSE'));
  fs.writeFileSync(path.join(OUT, 'pdf.classic.js'), toClassic(fs.readFileSync(path.join(OUT, 'pdf.min.mjs'), 'utf8'), 'pdfjsLib'));
  fs.writeFileSync(path.join(OUT, 'pdf.worker.classic.js'), toClassic(fs.readFileSync(path.join(OUT, 'pdf.worker.min.mjs'), 'utf8'), null));
  const files = ['pdf.min.mjs', 'pdf.worker.min.mjs', 'pdf.classic.js', 'pdf.worker.classic.js'];
  fs.writeFileSync(path.join(OUT, 'VERSION'), [
    `pdf.js (pdfjs-dist) ${version}, Apache License 2.0 (LICENSE in this folder)`,
    `source: https://registry.npmjs.org/pdfjs-dist/-/pdfjs-dist-${version}.tgz`,
    `npm-integrity: ${integrity}`,
    'The .mjs files are build/pdf.min.mjs and build/pdf.worker.min.mjs, unchanged; the .classic.js files are generated',
    'from them by tools/vendor-pdfjs.js. Update all four together.',
  ].concat(files.map((f) => `sha256 ${f} ${sha256(path.join(OUT, f))}`)).join('\n') + '\n');
  console.log('vendor/pdfjs: pdf.js ' + version + '\n' + fs.readFileSync(path.join(OUT, 'VERSION'), 'utf8'));
}
module.exports = { toClassic };
